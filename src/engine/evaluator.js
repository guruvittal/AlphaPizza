/**
 * Compare Legacy vs AI Generated engines for a given cart & inventory
 */
export function computeEngineComparison(cartItems, storeInventory, activeHeuristic, weights) {
  const cartSummary = computeCartTotals(cartItems);
  const legacy = evaluateLegacyEngine(cartSummary);
  const alphaEvolve = evaluateAlphaEvolveEngine(cartSummary, storeInventory, activeHeuristic, weights);

  const marginDeltaDollars = Math.round((alphaEvolve.storeNetMarginDollars - legacy.storeNetMarginDollars) * 100) / 100;
  const marginDeltaPct = Math.round((alphaEvolve.storeNetMarginPct - legacy.storeNetMarginPct) * 10) / 10;
  const savingsDeltaDollars = Math.round((alphaEvolve.customerSavings - legacy.customerSavings) * 100) / 100;
  const priceDeltaDollars = Math.round((alphaEvolve.customerFinalPrice - legacy.customerFinalPrice) * 100) / 100;

  return {
    cartSummary,
    legacy,
    alphaEvolve,
    comparison: {
      marginDeltaDollars,
      marginDeltaPct,
      savingsDeltaDollars,
      priceDeltaDollars,
      winner: marginDeltaDollars >= 0 ? "AI_GENERATED" : "LEGACY",
      summaryReason: marginDeltaDollars >= 0
        ? `AI Generated Deals delivered +$${marginDeltaDollars.toFixed(2)} higher store net profit ($${alphaEvolve.storeNetMarginDollars.toFixed(2)} vs $${legacy.storeNetMarginDollars.toFixed(2)}) while giving the customer $${alphaEvolve.customerSavings.toFixed(2)} total value saved!`
        : `Equal margin performance.`
    }
  };
}
