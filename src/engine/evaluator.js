import { MENU_ITEMS } from "../data/menuCatalog";

/**
 * Helper to compute cart financial metrics
 */
export function computeCartTotals(cartItems) {
  let retailSubtotal = 0;
  let totalCogs = 0;
  let totalItemCount = 0;
  let pizzaCount = 0;
  let sideCount = 0;
  let dessertCount = 0;
  let beverageCount = 0;

  const itemDetails = cartItems.map((ci) => {
    const catalogItem = MENU_ITEMS.find((m) => m.id === ci.itemId) || {
      name: "Custom Item",
      retailPrice: 10.0,
      cogs: 2.0,
      category: "other"
    };
    const lineRetail = catalogItem.retailPrice * ci.quantity;
    const lineCogs = catalogItem.cogs * ci.quantity;

    retailSubtotal += lineRetail;
    totalCogs += lineCogs;
    totalItemCount += ci.quantity;

    if (catalogItem.category === "pizza") pizzaCount += ci.quantity;
    if (catalogItem.category === "side") sideCount += ci.quantity;
    if (catalogItem.category === "dessert") dessertCount += ci.quantity;
    if (catalogItem.category === "beverage") beverageCount += ci.quantity;

    return {
      ...catalogItem,
      quantity: ci.quantity,
      lineRetail,
      lineCogs,
      isAttachedDealItem: Boolean(ci.isAttachedDealItem)
    };
  });

  return {
    itemDetails,
    retailSubtotal: Math.round(retailSubtotal * 100) / 100,
    totalCogs: Math.round(totalCogs * 100) / 100,
    totalItemCount,
    pizzaCount,
    sideCount,
    dessertCount,
    beverageCount
  };
}

/**
 * Execute Legacy Static 20% Coupon Heuristic
 */
export function evaluateLegacyEngine(cartSummary) {
  const { retailSubtotal, totalCogs } = cartSummary;
  const discount = Math.round(retailSubtotal * 0.20 * 100) / 100;
  const finalPrice = Math.round(Math.max(0, retailSubtotal - discount) * 100) / 100;
  const netMarginDollars = Math.round((finalPrice - totalCogs) * 100) / 100;
  const netMarginPct = finalPrice > 0 ? Math.round((netMarginDollars / finalPrice) * 1000) / 10 : 0;

  return {
    engineName: "Legacy Static Coupon Engine",
    promoId: "LEGACY_20_OFF",
    promoName: "Standard 20% Off Cart Coupon",
    discountAmount: discount,
    customerFinalPrice: finalPrice,
    customerSavings: discount,
    customerSavingsPct: retailSubtotal > 0 ? Math.round((discount / retailSubtotal) * 1000) / 10 : 0,
    attachedItemSku: null,
    attachedItemName: null,
    attachedPrice: 0,
    attachedCogs: 0,
    storeNetMarginDollars: netMarginDollars,
    storeNetMarginPct: netMarginPct,
    surplusCleared: false,
    executionTimeMs: 1.2,
    ruleType: "Static Rule",
    inventoryAttachScore: 0
  };
}

